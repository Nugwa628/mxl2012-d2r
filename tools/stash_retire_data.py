"""Generate the bounded extended-save reader tables used by stash retirement."""
import json
from pathlib import Path
import d2save
ROOT = Path(__file__).resolve().parents[1]
def generate():
    t = d2save.Tables.from_excel()
    out = ['// Generated by tools/stash_retire_data.py; do not edit.', '#pragma once', '#include <map>', '#include <set>', '#include <string>', 'namespace stash_retire {', 'struct Stat { unsigned bits, par, csv, csvpar; int add; };', 'inline const std::map<unsigned, Stat> Stats = {']
    for i,s in sorted(t.stats.items()):
        out.append('{%d,{%d,%d,%d,%d,%d}},' % (i,s['bits'],s['par'],s['csv_bits'] if s['saved'] else 0,s['csv_par'],s['add']))
    out += ['};']
    for name,values in [('Armor',t.armor),('Weapons',t.weapons),('Stackable',t.stackable),('Tomes',t.tomes),('Charms',t.charms),('BodyParts',t.bodyparts),('QuestDiff',t.questdiff)]:
        out += ['inline const std::set<std::string> '+name+' = {'+','.join(json.dumps(v) for v in sorted(values))+'};']
    codes = dict(d2save.HUFF)
    codes.update({k:d2save.HUFF_ESC+v for k,v in d2save.EXT_CODES.items()})
    out += ['inline const std::map<std::string,char> Codes = {']
    out += ['{'+json.dumps(v)+', '+'static_cast<char>('+str(ord(k))+')},' for k,v in codes.items()]
    out += ['};', '}']
    return '\n'.join(out)+'\n'
if __name__ == '__main__':
    (ROOT/'plugin/src/stash_retire_data.h').write_text(generate(),encoding='utf-8')
