r"""Engine-code audit of Median XL 2012's tables against 1.13c vanilla and D2R 93847 (docs/engine-triage.md).

  py -3 -I tools/engine_audit.py <extract-root> [out.md]

<extract-root> is an extracted patch_d2.mpq (mxl2012-runs\extract-mpq). Median XL 2012 is pure data for 1.13c, so every
function number in its tables names a 1.13c engine function. For each function column the audit sorts Median's values:

  same      a vanilla 1.13c row uses the number and D2R keeps the same number for that vanilla row
  moved     a vanilla 1.13c row uses it but D2R renumbered / blanked that cell (tools/vanilla113.py CELLS_113C)
  new113    no vanilla 1.13c row uses it: the slot exists in 1.13c's table but its D2R meaning is unverified
            ("d2r-uses" = a D2R row uses the number, so the slot is filled in D2R, possibly with another function)

and lists the Median rows on each value that is not "same". The 1.13c view is tools/vanilla113.py's.
"""
from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import vanilla113  # noqa: E402

D2R = vanilla113.D2R_BASE

SKILL_COLS = ["srvstfunc", "srvdofunc", "srvprgfunc1", "srvprgfunc2", "srvprgfunc3", "cltstfunc", "cltdofunc",
              "cltprgfunc1", "cltprgfunc2", "cltprgfunc3", "auraeventfunc1", "auraeventfunc2", "auraeventfunc3",
              "ItemEffect", "ItemCltEffect", "pettype"]
MISSILE_COLS = ["pCltDoFunc", "pCltHitFunc", "pSrvDoFunc", "pSrvHitFunc", "pSrvDmgFunc", "SrvCalc1", "CltCalc1",
                "CollideType"]
OTHER = {  # table -> (key column, columns); only tables with a 1.13c view row count
    "itemstatcost": ("Stat", ["op", "descfunc", "dgrpfunc", "Encode", "descval"]),
    "properties": ("code", ["func1", "func2", "func3", "func4", "func5", "func6", "func7"]),
    "states": ("state", ["setfunc", "remfunc", "cltactivefunc", "srvactivefunc"]),
    "objects": ("Name", ["OperateFn", "PopulateFn", "InitFn", "ClientFn", "SubClass"]),
    "levels": ("Name", ["LevelType", "DrlgType"]),
    "monstats": ("Id", ["AI"]),
    "shrines": ("Shrine name", ["Code"]),
}


def read(p: Path):
    text = p.read_text("latin-1")
    lines = text.split("\r\n") if "\r\n" in text else text.split("\n")
    h = lines[0].split("\t")
    rows = []
    for l in lines[1:]:
        if not l.strip("\t "):
            continue
        r = l.split("\t")
        r.extend([""] * (len(h) - len(r)))
        rows.append(r)
    return h, rows


def values(h, rows, col, key):
    out = defaultdict(list)
    if col not in h:
        return out
    c, k = h.index(col), h.index(key) if key in h else 0
    for r in rows:
        v = r[c].strip()
        if v:
            out[v].append(r[k])
    return out


def vanilla_rows(table):
    """(header, rows) of 1.13c (the view), or None when the view has no row count for the table."""
    if table not in vanilla113.ROW_COUNTS:
        return None
    return vanilla113.load(table, read)


def audit(root: Path, table: str, key: str, cols: list[str], lines: list[str]) -> None:
    mh, mr = read(root / "data" / "global" / "excel" / f"{table}.txt")
    dh, dr = read(D2R / f"{table}.txt")
    view = vanilla_rows(table)
    moved_cells = vanilla113.CELLS_113C.get(table, {})
    lines.append(f"\n## {table}.txt ({len(mr)} Median rows)\n")
    for col in cols:
        mv = values(mh, mr, col, key)
        if not mv:
            continue
        dv = values(dh, dr, col, key)
        vv = values(*view, col, key if key in view[0] else view[0][0]) if view else {}
        moved = {v for (i, c), v in moved_cells.items() if c == col and v}
        same, odd = [], []
        for v in sorted(mv, key=lambda s: (len(s), s)):
            if v in moved:
                odd.append((v, "moved", mv[v]))
            elif not view:
                odd.append((v, "d2r-uses" if v in dv else "d2r-unused", mv[v])) if v not in dv else same.append(v)
            elif v in vv:
                same.append(v)
            else:
                odd.append((v, "new113, d2r-uses" if v in dv else "new113, d2r-unused", mv[v]))
        lines.append(f"- **{col}**: {len(mv)} values; same as vanilla: {len(same)}; flagged: {len(odd)}")
        for v, why, names in odd:
            show = ", ".join(n for n in names[:6])
            more = f" (+{len(names) - 6})" if len(names) > 6 else ""
            lines.append(f"  - `{v}` [{why}] {len(names)} rows: {show}{more}")


def main() -> None:
    root = Path(sys.argv[1])
    lines = ["# Engine audit (generated by tools/engine_audit.py)", "",
             f"Median tables: `{root}`; D2R base: `{D2R}`; 1.13c view: tools/vanilla113.py."]
    audit(root, "skills", "skill", SKILL_COLS, lines)
    audit(root, "missiles", "Missile", MISSILE_COLS, lines)
    for t, (k, cols) in OTHER.items():
        audit(root, t, k, cols, lines)
    out = "\n".join(lines) + "\n"
    if len(sys.argv) > 2:
        Path(sys.argv[2]).write_text(out, "utf-8")
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
