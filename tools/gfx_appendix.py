"""Build the generated appendix of docs/graphics-inventory.md from the survey outputs (read-only inputs).

    py -3 -I tools/gfx_appendix.py --survey <gfxsurvey-out\\mpq> --monsters <gfxsurvey-out\\monsters> --out <appendix.md>
"""
import argparse
import json
import os
from collections import defaultdict


def section(text, name, nxt):
    i = text.index(name)
    j = text.index(nxt, i + len(name)) if nxt else len(text)
    return text[i + len(name):j].strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--survey", required=True)
    ap.add_argument("--monsters", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    with open(os.path.join(a.survey, "gfx-tables.md"), encoding="utf-8") as f:
        tables = f.read()
    with open(os.path.join(a.survey, "lists.json"), encoding="utf-8") as f:
        lists = json.load(f)
    with open(os.path.join(a.monsters, "monster-compare.md"), encoding="utf-8") as f:
        monsters = f.read().strip()

    folder = section(tables, "## By folder", "## Item icons")
    out = []
    out.append("## Appendix A. Folders, pure v005 (generated by `tools/gfx_survey.py`)\n")
    out.append("Files per folder in `extract-mpq`. \"in D2R\": same path in the D2R filelist. NEW: no D2R path.\n")
    out.append(folder)

    out.append("\n## Appendix B. Monster sets against the reference set (generated by `tools/gfx_monster_cmp.py`)\n")
    out.append("\"in reference\": the reference set has a monster folder of that token. \"same file names\": its DCC/COF names "
               "match the reference set's. \"reference HD donor\": the reference `hd_monsters.md` donor for that Code and its "
               "confidence (for the HD client only).\n")
    out.append(monsters)

    out.append("\n## Appendix C. Item codes not in D2R's armor, weapon or misc tables (codes only)\n")
    out.append("\"dc6 in mod\": the item icon is in the mod tree. \"dc6 in D2R\": a D2R file at that path (the stand-in). "
               "Two codes have neither.\n")
    rows = ["| invfile | dc6 in mod | dc6 in D2R | item rows |", "|---|---|---|---:|"]
    for entry in lists["new_inv"]:
        v, in_mod, in_base, n = entry[0], entry[1], entry[2], entry[3]
        rows.append("| %s | %s | %s | %d |" % (v, "yes" if in_mod else "no", "yes" if in_base else "**no**", n))
    out.append("\n".join(rows))

    out.append("\n## Appendix D. Maps, missiles, overlays, unresolved names\n")
    groups = defaultdict(list)
    for p in lists["dt1_new"]:
        groups["/".join(p.split("/")[:5])].append(p.rsplit("/", 1)[1])
    out.append("**New DT1 (%d), by tileset:**\n" % len(lists["dt1_new"]))
    for k in sorted(groups):
        out.append("- `%s`: %s" % (k.replace("data/global/tiles/", ""), ", ".join(sorted(groups[k]))))
    out.append("\n**New DS1 (%d):** %s\n" % (
        len(lists["ds1_new"]), ", ".join("`%s`" % p.replace("data/global/tiles/", "") for p in lists["ds1_new"])))
    out.append("**New missile DCCs (%d):** %s\n" % (
        len(lists["mis_new"]), ", ".join(p.rsplit("/", 1)[1][:-4] for p in lists["mis_new"])))
    out.append("**New overlay DCCs (%d):** %s\n" % (
        len(lists["ovl_new"]), ", ".join(p.rsplit("/", 1)[1][:-4] for p in lists["ovl_new"])))
    out.append("**Unresolved (%d):** %s\n" % (
        len(lists["new_unresolved"]), ", ".join(lists["new_unresolved"])))

    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
